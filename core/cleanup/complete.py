"""High-frequency completion (SPEC 6.4.2 step 5).

Standard path: deterministic DSP only. The band just below the HF ceiling is
isolated, half-wave rectified (which generates harmonics and keeps the
temporal envelope of the source), band-limited to the region above the
ceiling and level matched to the extrapolated long-term spectral slope minus
a safety margin, with a further fade towards the top. Nothing is learned or
generated by a model; the same input gives the same output.

Neural completion is *not* in the standard path (D-041). The hook
:func:`neural_completion` exists so that a licensed model from the registry
can be wired in later; it refuses to run unless explicitly enabled with a
registry model, and there is no backend in this build.
"""

from __future__ import annotations

import numpy as np
from scipy import fft as sfft
from scipy import ndimage

from ..errors import EnvironmentProblem, ValidationError
from ._util import EPS, v

METHOD_DSP = "dsp_harmonic"
METHOD_NEURAL = "neural"


def complete_hf(x2d: np.ndarray, sr: float, ceiling_hz: float, policy: dict) -> tuple[np.ndarray, dict]:
    """Return (added component [frames, channels], record)."""
    cp = policy["completion"]
    n, nch = x2d.shape
    nyq = sr / 2.0
    src_bw = float(v(cp["source_bw_hz"]))
    f_lo = max(1000.0, ceiling_hz - src_bw)
    f_top = min(ceiling_hz + float(v(cp["extend_hz"])), float(v(cp["max_hz"])), 0.95 * nyq)
    record = {"method": METHOD_DSP, "neural": False, "deterministic": True,
              "note": "deterministic DSP (half-wave rectification harmonics), not a generative model",
              "ceiling_hz": ceiling_hz, "source_band_hz": [round(f_lo, 1), round(ceiling_hz, 1)],
              "target_band_hz": [round(ceiling_hz, 1), round(f_top, 1)]}
    added = np.zeros_like(x2d)
    if f_top - ceiling_hz < 200.0:
        record["skipped"] = "no room above the ceiling"
        return added, record
    pad = max(int(sr // 2), 4096)
    nfft = sfft.next_fast_len(n + pad, real=True)
    f = np.arange(nfft // 2 + 1) * (sr / nfft)
    df = sr / nfft
    src_mask = ((f >= f_lo) & (f < ceiling_hz - 100.0)).astype(np.float64)
    tgt = (f >= ceiling_hz) & (f < f_top)
    fit0, fit1 = v(cp["fit_window_hz"])
    fit = (f >= ceiling_hz - float(fit0)) & (f < ceiling_hz - float(fit1))
    sm = max(1, int(round(200.0 / df)))
    margin = float(v(cp["margin_db"]))
    fade = float(v(cp["fade_db_per_khz"]))
    max_gain = float(v(cp["max_gain_db"]))
    slopes = []
    for c in range(nch):
        X = sfft.rfft(x2d[:, c], nfft)
        px = ndimage.uniform_filter1d(X.real ** 2 + X.imag ** 2, sm, mode="nearest")
        if not np.any(fit) or float(np.mean(px[fit])) <= 0.0:
            continue
        # extrapolated LTAS slope (dB per Hz) from the band below the ceiling
        ff = f[fit]
        ld = 10.0 * np.log10(px[fit] + EPS)
        a, b = np.polyfit((ff - ceiling_hz) / 1000.0, ld, 1)
        slopes.append(float(a))
        a = min(a, 0.0)  # never extrapolate a rising spectrum
        src = sfft.irfft(X * src_mask, nfft)[:n]
        rect = np.maximum(src, 0.0)
        rect -= rect.mean()
        R = sfft.rfft(rect, nfft)
        pr = ndimage.uniform_filter1d(R.real ** 2 + R.imag ** 2, sm, mode="nearest")
        khz = (f[tgt] - ceiling_hz) / 1000.0
        target_db = b + a * khz - margin - fade * khz
        gain_db = target_db - 10.0 * np.log10(pr[tgt] + EPS)
        gain_db = np.minimum(gain_db, max_gain)
        h = np.zeros_like(f)
        h[tgt] = 10.0 ** (gain_db / 20.0)
        # short raised-cosine edges to avoid ringing at the band limits
        edge = max(2, int(round(100.0 / df)))
        idx = np.flatnonzero(tgt)
        if idx.size > 2 * edge:
            ramp = 0.5 - 0.5 * np.cos(np.linspace(0.0, np.pi, edge))
            h[idx[:edge]] *= ramp
            h[idx[-edge:]] *= ramp[::-1]
        added[:, c] = sfft.irfft(R * h, nfft)[:n]
    record["fitted_slope_db_per_khz"] = [round(s, 3) for s in slopes]
    record["margin_db"] = margin
    record["added_rms_dbfs"] = round(float(10.0 * np.log10(np.mean(added ** 2) + 1e-30)), 2)
    return added, record


def neural_completion(x, sr: float, *, enabled: bool = False, model: str | None = None):
    """Hook for model-based HF completion (outside the standard path, D-041).

    Refuses unless ``enabled`` is True *and* a registry model id is given.
    Even then this build has no neural backend, so it raises. A future
    implementation must record "HF completed by a generative model" in the
    Mix Report and pass the license check (S-10).
    """
    if not enabled:
        raise ValidationError(
            "neural HF completion is disabled: it is not part of the standard path (D-041); "
            "enable it explicitly and give a registry model",
            details={"decision": "D-041"})
    if not model:
        raise ValidationError(
            "neural HF completion needs a model from the model registry (SPEC 12)",
            details={"decision": "D-041"})
    raise EnvironmentProblem(
        f"neural HF completion backend is not available in this build (model '{model}')",
        details={"decision": "D-041", "model": model})
